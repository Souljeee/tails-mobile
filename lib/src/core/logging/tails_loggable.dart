/// Событие или состояние, которое умеет безопасно описать себя для журнала.
///
/// По умолчанию `TailsBlocObserver` пишет только имя типа: `toString()` может содержать
/// персональные данные. Если по записи нужно видеть и содержимое, реализуйте этот интерфейс
/// и верните только то, что можно хранить в журнале (идентификаторы, счётчики, флаги).
/// Значения всё равно проходят через санитайзер.
abstract interface class TailsLoggable {
  /// Поля для журнала.
  Map<String, Object?> toLogData();
}
